function isVehicleTaxi(vehicle)
    if not isElement(vehicle) or getElementType(vehicle) ~= "vehicle" then
        return false
    end
    if isTaxiPlateRegistered then
        return isTaxiPlateRegistered(getVehiclePlateText(vehicle))
    end
    local plate = getElementData(vehicle, "taxi:plate") or getElementData(vehicle, "veh:plate") or getVehiclePlateText(vehicle)
    if getElementData(vehicle, "taxi:isTaxi") == true then
        return true
    end
    if plate then
        local plateUpper = string.upper(tostring(plate))
        if string.match(plateUpper, "^%d%d%s*T%s*%d+$") then
            return true
        end
    end
    return false
end

function getTaxiVehicleRating(vehicle)
    if not isElement(vehicle) or getElementType(vehicle) ~= "vehicle" then
        return 0
    end
    local customRating = tonumber(getElementData(vehicle, "taxi:rating"))
    if customRating then
        return math.max(1.0, math.min(5.0, customRating))
    end
    return TaxiConfig.VehicleRatings[getElementModel(vehicle)] or TaxiConfig.DefaultVehicleRating
end

function getVehicleTaxiPlate(vehicle)
    if not isElement(vehicle) or getElementType(vehicle) ~= "vehicle" then
        return nil
    end
    if isTaxiPlateRegistered then
        return getVehiclePlateText(vehicle)
    end
    return getElementData(vehicle, "taxi:plate") or getElementData(vehicle, "veh:plate") or getVehiclePlateText(vehicle)
end